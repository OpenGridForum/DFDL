"""Generate the shaded matrix tables from their data files.

Clause 14's two separator suppression tables are matrices of merged, coloured
cells.  Written out as AsciiDoc, every merge is a span count and every colour
a per-cell style, and the irregular coloured regions need borders switched off
cell by cell.  That source is hard to read and easy to break, so each table is
kept instead as a data file under ``spec/tables/`` and this tool writes the
AsciiDoc.

A data file is a few settings followed by the grid, one row at a time::

    title: Separator Suppression for dfdl:occursCountKind 'implicit'
    widths: 27 10 10 14 13 11 15
    header-rows: 4
    colour grey #DBDBDB

    never
    grey: Schema definition error
    <
    ...

Rows are separated by a blank line, and a row lists one line per column.  A
cell is its text, optionally preceded by a colour name and a colon.  ``^``
continues the cell above and ``<`` the cell to the left, so a merged cell is
written once and its extent is visible in the grid.  ``.`` is an empty white
cell; ``grey:`` alone is an empty shaded one.  Text is written as it should
read: the tool escapes anything AsciiDoc would rewrite.

Shaded regions run into each other without a rule between them, as in the
draft; white cells keep their borders.  Header rows are bold.

The output replaces the table in the clause file between two marker comments,
so the clause still reads correctly in GitHub's preview, which doesn't follow
includes.  ``--check`` reports any table that no longer matches its data file.

Usage::

    python3 tools/tables.py           # rewrite the generated tables
    python3 tools/tables.py --check   # fail if any is out of date
"""

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLES = ROOT / "spec" / "tables"
CLAUSES = ROOT / "spec" / "clauses"

BEGIN = "// Generated by tools/tables.py from tables/{name}. Edit that file, not this table."
END = "// End of generated table."

# Sequences AsciiDoc replaces even in a table cell: arrows, an ellipsis, an
# em dash, and the symbol shorthands.
REPLACED = re.compile(r"=>|<=|->|<-|\.\.\.|--|\((?:C|R|TM)\)")

SIDES = {"top": (-1, 0), "bottom": (1, 0), "left": (0, -1), "right": (0, 1)}


@dataclass
class Cell:
    text: str
    colour: str | None
    positions: list = field(default_factory=list)


@dataclass
class Table:
    name: str
    title: str = ""
    widths: list = field(default_factory=list)
    header_rows: int = 0
    colours: dict = field(default_factory=dict)
    grid: list = field(default_factory=list)  # rows of Cell references


def fail(table, message):
    sys.exit(f"tables.py: {table}: {message}")


def parse(path):
    table = Table(path.name)
    lines = path.read_text().split("\n")
    rows, current = [], []
    in_grid = False
    for line in lines:
        if line.startswith("#"):
            continue
        if not in_grid:
            key, _, value = line.partition(":")
            if line.startswith("colour "):
                _, name, hexcode = line.split()
                table.colours[name] = hexcode
            elif key == "title":
                table.title = value.strip()
            elif key == "widths":
                table.widths = value.split()
            elif key == "header-rows":
                table.header_rows = int(value)
            elif line.strip():
                in_grid = True
        if in_grid:
            if line.strip():
                current.append(line.strip())
            elif current:
                rows.append(current)
                current = []
    if current:
        rows.append(current)
    if not table.title or not table.widths:
        fail(path.name, "needs a title and widths")
    build_grid(table, rows)
    return table


def parse_cell(table, token):
    if token == ".":
        return Cell("", None)
    name, colon, rest = token.partition(":")
    if colon and name in table.colours:
        return Cell(rest.strip(), name)
    return Cell(token, None)


def build_grid(table, rows):
    width = len(table.widths)
    for r, row in enumerate(rows):
        if len(row) != width:
            fail(table.name, f"row {r + 1} has {len(row)} cells, expected {width}")
        out = []
        for c, token in enumerate(row):
            if token == "^":
                if r == 0:
                    fail(table.name, f"row 1 column {c + 1} continues nothing")
                cell = table.grid[r - 1][c]
            elif token == "<":
                if c == 0:
                    fail(table.name, f"row {r + 1} column 1 continues nothing")
                cell = out[c - 1]
            else:
                cell = parse_cell(table, token)
            cell.positions.append((r, c))
            out.append(cell)
        table.grid.append(out)
    for cell in {id(c): c for row in table.grid for c in row}.values():
        rs = {p[0] for p in cell.positions}
        cs = {p[1] for p in cell.positions}
        if len(cell.positions) != len(rs) * len(cs):
            r, c = cell.positions[0]
            fail(table.name, f"cell at row {r + 1} column {c + 1} is not a rectangle")


def escape(text):
    text = text.replace("|", "\\|")
    return REPLACED.sub(lambda m: f"+{m.group(0)}+", text)


def open_sides(table, cell):
    """Sides of a shaded cell whose neighbours are all shaded."""
    rows = len(table.grid)
    sides = []
    for side, (dr, dc) in SIDES.items():
        neighbours = []
        for r, c in cell.positions:
            nr, nc = r + dr, c + dc
            if not (0 <= nr < rows and 0 <= nc < len(table.widths)):
                continue
            other = table.grid[nr][nc]
            if other is not cell:
                neighbours.append((nr, other))
        if neighbours and all(
            other.colour and nr >= table.header_rows for nr, other in neighbours
        ):
            sides.append(side)
    return sides


def render(table):
    cols = ",".join(f"^.^{w}" for w in table.widths)
    out = [
        BEGIN.format(name=table.name),
        f".{table.title}",
        f'[cols="{cols}",headerrows={table.header_rows},keep-lines-together=true]',
        "|===",
    ]
    for r, row in enumerate(table.grid):
        out.append("")
        for c, cell in enumerate(row):
            if cell.positions[0] != (r, c):
                continue
            rs = len({p[0] for p in cell.positions})
            cs = len({p[1] for p in cell.positions})
            span = (str(cs) if cs > 1 else "") + (f".{rs}" if rs > 1 else "")
            spec = f"{span}+| " if span else "| "
            text = escape(cell.text)
            if text and r < table.header_rows:
                text = f"*{text}*"
            if cell.colour:
                style = [f"background-color:{table.colours[cell.colour]}"]
                style += [f"border-{s}:none" for s in open_sides(table, cell)]
                text = f"td-style:[{';'.join(style)}] {text}".rstrip()
            out.append(f"{spec}{text}".rstrip())
    out += ["|===", END]
    return out


def splice(clause_text, table, generated):
    lines = clause_text.split("\n")
    begin = BEGIN.format(name=table.name)
    if begin not in lines:
        return None
    start = lines.index(begin)
    end = lines.index(END, start)
    return "\n".join(lines[:start] + generated + lines[end + 1 :])


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="report stale tables")
    args = parser.parse_args()

    stale = []
    for path in sorted(TABLES.glob("*.txt")):
        table = parse(path)
        generated = render(table)
        for clause in sorted(CLAUSES.glob("*.adoc")):
            old = clause.read_text()
            new = splice(old, table, generated)
            if new is None:
                continue
            if new != old:
                if args.check:
                    stale.append(f"{clause.name}: {path.name}")
                else:
                    clause.write_text(new)
                    print(f"updated {clause.name} from {path.name}")
            break
        else:
            fail(path.name, "no clause carries its marker comment")
    if stale:
        print("Generated tables out of date; run `make tables`:", file=sys.stderr)
        print("\n".join(f"  {s}" for s in stale), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
