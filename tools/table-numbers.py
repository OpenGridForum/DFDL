"""Keep the table numbers in the specification fixed.

Readers and other documents cite DFDL tables by number, so a table added to
the specification must not renumber the tables after it.  Metanorma counts
tables itself, which would do exactly that, so every table with a caption
states its number in the source with a ``number=`` attribute instead, and
this tool keeps those numbers in order.

A table in the body is numbered 1, 2, 3 and so on.  A table in an annex is
numbered from 1 again and prints with the annex letter, as A.1.  A new table
takes the number of the table before it plus a letter: 33-A after 33, then
33-B.  Removing a table leaves a gap rather than renumbering the rest.

Without ``--check``, the tool gives a number to every captioned table that has
none, following that rule, and says what it wrote; ``make xml``, ``make html``
and ``make pdf`` run it first.  A table that can't follow the rule, such as a
new first table in an annex that already has a Table 1, has to be numbered by
hand.  The two tables ``tools/tables.py`` generates take their number from
their data files under ``spec/tables/``.

``--check`` fails if a captioned table has no number, a number is malformed or
used twice, or the numbers are out of order.

Usage::

    python3 tools/table-numbers.py           # number any table that has none
    python3 tools/table-numbers.py --check   # make check
"""

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MASTER = ROOT / "spec" / "dfdl-ogf.adoc"

# Files whose includes are followed: the masters' front matter and body.
CONTAINERS = ("front.adoc", "body.adoc")

DELIMITERS = re.compile(r"(-{4,}|\.{4,}|/{4,}|\+{4,})")
NUMBER = re.compile(r"(\d+)(?:-([A-Z]))?")
NUMBER_ATTR = re.compile(r'(?<=[\[,])number=(?:"([^"]*)"|([^,\]]*))')
GENERATED = "// Generated by tools/tables.py"


@dataclass
class Table:
    path: Path
    open_line: int  # index of the opening |=== line
    attr_line: int | None  # index of its attribute list, if any
    caption: str
    sequence: str  # "body", or the annex's file name
    number: str | None
    generated: bool

    @property
    def where(self):
        return f"{self.path.relative_to(ROOT)}:{self.open_line + 1}"

    @property
    def label(self):
        return f'{self.where} "{self.caption}"'


def included(path):
    files = []
    for line in path.read_text().splitlines():
        m = re.match(r"include::([^\[]+)\[\]", line)
        if m:
            target = (path.parent / m.group(1)).resolve()
            files += included(target) if target.name in CONTAINERS else [target]
    return files


def tables_in(path):
    lines = path.read_text().splitlines()
    annex = bool(lines) and lines[0].startswith("[appendix")
    sequence = path.name if annex else "body"
    found = []
    delimiter = None
    i = 0
    while i < len(lines):
        line = lines[i]
        if delimiter:
            if line == delimiter:
                delimiter = None
            i += 1
            continue
        if DELIMITERS.fullmatch(line):
            delimiter = line
            i += 1
            continue
        if line != "|===":
            i += 1
            continue
        caption = None
        attr_line = None
        generated = False
        j = i - 1
        while j >= 0 and lines[j][:1] in (".", "[", "/"):
            text = lines[j]
            if text.startswith(GENERATED):
                generated = True
            elif text.startswith(".") and not text.startswith(".."):
                caption = text[1:]
            elif text.startswith("[") and not text.startswith("[["):
                attr_line = j
            j -= 1
        number = None
        if attr_line is not None:
            m = NUMBER_ATTR.search(lines[attr_line])
            if m:
                number = m.group(1) if m.group(1) is not None else m.group(2)
        if caption:
            found.append(
                Table(path, i, attr_line, caption, sequence, number, generated)
            )
        i += 1
        while i < len(lines) and lines[i] != "|===":
            i += 1
        i += 1
    return found


def all_tables():
    return [t for path in included(MASTER) for t in tables_in(path)]


def key(number):
    m = NUMBER.fullmatch(number)
    return (int(m.group(1)), m.group(2) or "")


def next_after(number):
    """The number for a table placed straight after ``number``."""
    n, letter = key(number)
    if not letter:
        return f"{n}-A"
    if letter == "Z":
        return None
    return f"{n}-{chr(ord(letter) + 1)}"


def check(tables):
    errors = []
    last = {}
    seen = {}
    for t in tables:
        if t.number is None:
            errors.append(f"{t.label} has no number")
            continue
        if not NUMBER.fullmatch(t.number):
            errors.append(
                f'{t.label} has number "{t.number}"; expected e.g. 12 or 12-A'
            )
            continue
        first = seen.setdefault((t.sequence, t.number), t)
        if first is not t:
            errors.append(f"{t.label} repeats number {t.number} from {first.where}")
            continue
        previous = last.get(t.sequence)
        if previous and key(t.number) <= key(previous.number):
            errors.append(
                f"{t.label} is numbered {t.number}, after {previous.number} at "
                f"{previous.where}"
            )
        last[t.sequence] = t
    return errors


def number_missing(tables):
    """Give each table without a number the next number after its predecessor."""
    errors = []
    edits = {}
    by_sequence = {}
    for t in tables:
        by_sequence.setdefault(t.sequence, []).append(t)
    for run in by_sequence.values():
        for i, t in enumerate(run):
            if t.number is not None:
                continue
            if t.generated:
                errors.append(
                    f"{t.label} needs a number: line in its spec/tables/ file"
                )
                continue
            previous = run[i - 1].number if i else None
            if previous is None:
                proposed = "1"
            elif NUMBER.fullmatch(previous):
                proposed = next_after(previous)
            else:
                proposed = None
            later = next((u.number for u in run[i + 1 :] if u.number), None)
            if (
                proposed is None
                or later is not None
                and NUMBER.fullmatch(later)
                and key(later) <= key(proposed)
            ):
                errors.append(f"{t.label} needs a number chosen by hand")
                continue
            t.number = proposed
            edits.setdefault(t.path, []).append(t)
    return edits, errors


def with_number(line, number):
    """The attribute list ``line`` with ``number`` added first."""
    inner = line[1:-1]
    first = inner.split(",", 1)[0]
    if "=" in first or not inner:
        return f'[number="{number}"' + ("," + inner if inner else "") + "]"
    # A positional first entry, such as %unnumbered or a style, stays first.
    return f'[{inner},number="{number}"]'


def write(edits):
    for path, tables in edits.items():
        lines = path.read_text().split("\n")
        # Bottom up, so inserting a line doesn't move the tables still to do.
        for t in sorted(tables, key=lambda t: t.open_line, reverse=True):
            if t.attr_line is not None:
                lines[t.attr_line] = with_number(lines[t.attr_line], t.number)
            else:
                lines.insert(t.open_line, f'[number="{t.number}"]')
            print(f"{t.label}: numbered {t.number}")
        path.write_text("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--check", action="store_true", help="report problems and change nothing"
    )
    args = parser.parse_args()

    tables = all_tables()
    if args.check:
        errors = check(tables)
    else:
        edits, errors = number_missing(tables)
        write(edits)
        # Any table still without a number was reported above.
        errors += check([t for t in tables if t.number is not None])
    for e in errors:
        print(e, file=sys.stderr)
    if errors:
        sys.exit(1)
    if args.check:
        print(f"All {len(tables)} captioned tables have their numbers in order.")


if __name__ == "__main__":
    main()
