"""Write the OGF edition's PDF stylesheet override.

The OGF edition needs everything in spec/pdf-overrides.xsl, which both
editions use, plus templates of its own: its header, footer and cover. mn2pdf
accepts a single override file and rejects a template that is defined twice,
so the shared file cannot simply be included. This joins the two instead:

  spec/pdf-overrides.xsl           both editions
  spec/pdf-overrides-ogf-only.xsl  the OGF edition only
  spec/pdf-overrides-ogf.xsl       the result, which spec/dfdl-ogf.adoc uses

The result is committed so it can be read with the rest of the source, and
``make check`` runs this with --check, which fails if it is out of date.

Some templates in these files replace metanorma-iso's own.  Each one carries
a fingerprint of the original it replaces, as a comment beside it:

    <!-- upstream: metanorma-iso refine_p-style sha256:... -->

A template with no name is identified by its match pattern instead:

    <!-- upstream: metanorma-iso match="mn:sourcecode/text()" sha256:... -->

With --image, --check also reads those originals from the Metanorma image and
fails if any no longer matches its fingerprint, so an image upgrade that
changes a template we depend on cannot pass unnoticed.  Review the change,
update the override, then the fingerprint the failure prints.

Usage::

    python3 tools/overrides.py                         # rewrite the OGF override
    python3 tools/overrides.py --check --image IMAGE   # make check
"""

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

SPEC = Path(__file__).resolve().parent.parent / "spec"
SHARED = SPEC / "pdf-overrides.xsl"
OGF_ONLY = SPEC / "pdf-overrides-ogf-only.xsl"
OUTPUT = SPEC / "pdf-overrides-ogf.xsl"

DECLARATION = '<?xml version="1.0" encoding="UTF-8"?>\n'
FO_NAMESPACE = 'xmlns:fo="http://www.w3.org/1999/XSL/Format"'
STYLESHEET = re.compile(r"<xsl:stylesheet[^>]*>(.*)</xsl:stylesheet>", re.DOTALL)
FINGERPRINT = re.compile(
    r'<!-- upstream: metanorma-iso ([\w-]+|match="[^"]+") sha256:([0-9a-f]{64}) -->'
)
UPSTREAM_XSL = "iso.international-standard.xsl"
NOTICE = """<!--
  Generated by tools/overrides.py from pdf-overrides.xsl and
  pdf-overrides-ogf-only.xsl. Do not edit it: change those and run
  `make overrides`. `make check` fails if this file is out of date.
-->
"""


def generate() -> str:
    """Return the OGF override: the shared file with the OGF templates added."""
    shared = SHARED.read_text(encoding="utf-8")
    ogf_only = OGF_ONLY.read_text(encoding="utf-8")

    body = STYLESHEET.search(ogf_only)
    if body is None:
        sys.exit(f"{OGF_ONLY.name}: no xsl:stylesheet element")
    if shared.count("</xsl:stylesheet>") != 1:
        sys.exit(f"{SHARED.name}: expected one closing xsl:stylesheet tag")

    # The OGF templates write XSL-FO directly, so the result needs its prefix.
    opening = re.search(r"<xsl:stylesheet[^>]*>", shared).group(0)
    if FO_NAMESPACE not in opening:
        widened = opening.replace(
            "<xsl:stylesheet ", f"<xsl:stylesheet {FO_NAMESPACE} ", 1
        )
        shared = shared.replace(opening, widened, 1)

    if shared.startswith(DECLARATION):
        shared = DECLARATION + NOTICE + shared[len(DECLARATION) :]
    else:
        shared = NOTICE + shared

    added = body.group(1).strip("\n")
    if not added.strip():
        return shared
    return shared.replace("</xsl:stylesheet>", f"{added}\n\n</xsl:stylesheet>")


def upstream_template(stylesheet: str, name: str) -> str | None:
    """The text of one template in metanorma-iso's stylesheet, by name or match."""
    if name.startswith('match="'):
        attribute = name
    else:
        # The name may sit beside other attributes, as in <xsl:template match="..." name="fn">.
        attribute = f'name="{name}"'
    pattern = rf"<xsl:template\b[^>]*\b{re.escape(attribute)}[^>]*>.*?</xsl:template>"
    found = re.findall(pattern, stylesheet, re.DOTALL)
    return found[0] if len(found) == 1 else None


def fingerprint(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def check_upstream(image: str) -> list[str]:
    """Problems with the fingerprinted templates, against the given image."""
    recorded = []
    for source in (SHARED, OGF_ONLY):
        for name, digest in FINGERPRINT.findall(source.read_text(encoding="utf-8")):
            recorded.append((source.name, name, digest))
    if not recorded:
        return []
    command = [
        "docker",
        "run",
        "--rm",
        image,
        "sh",
        "-c",
        f'cat "$(find / -name {UPSTREAM_XSL} 2>/dev/null | head -1)"',
    ]
    result = subprocess.run(command, check=False, capture_output=True, text=True)
    if result.returncode or not result.stdout:
        return [f"could not read {UPSTREAM_XSL} from {image}"]
    problems = []
    for source, name, digest in recorded:
        text = upstream_template(result.stdout, name)
        if text is None:
            problems.append(f"{source}: {name} is no longer one template in {image}")
        elif fingerprint(text) != digest:
            problems.append(
                f"{source}: metanorma-iso's {name} has changed in {image}. "
                f"Review the override, then record sha256:{fingerprint(text)}"
            )
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if spec/pdf-overrides-ogf.xsl is out of date",
    )
    parser.add_argument(
        "--image",
        help="with --check, also compare the overridden templates with this image",
    )
    args = parser.parse_args(argv)

    expected = generate()
    name = OUTPUT.relative_to(SPEC.parent)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != expected:
            print(f"{name} is out of date; run `make overrides`.", file=sys.stderr)
            return 1
        print(f"{name} is up to date.")
        if args.image:
            problems = check_upstream(args.image)
            for problem in problems:
                print(problem, file=sys.stderr)
            if problems:
                return 1
            print(f"The overridden templates match {args.image}.")
        return 0

    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"wrote {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
