"""Write the OGF edition's PDF stylesheet override.

The OGF edition needs everything in spec/pdf-overrides.xsl, which both
editions use, plus templates of its own: its header, footer and cover. mn2pdf
accepts a single override file and rejects a template that is defined twice,
so the shared file cannot simply be included. This joins the two instead:

  spec/pdf-overrides.xsl           both editions
  spec/pdf-overrides-ogf-only.xsl  the OGF edition only
  spec/pdf-overrides-ogf.xsl       the result, which spec/dfdl-ogf.adoc uses

The result is committed so it can be read with the rest of the source, and
``make check`` runs this with --check, which fails if it is out of date.

Usage::

    python3 tools/overrides.py           # rewrite spec/pdf-overrides-ogf.xsl
    python3 tools/overrides.py --check   # fail if it is out of date
"""

import argparse
import re
import sys
from pathlib import Path

SPEC = Path(__file__).resolve().parent.parent / "spec"
SHARED = SPEC / "pdf-overrides.xsl"
OGF_ONLY = SPEC / "pdf-overrides-ogf-only.xsl"
OUTPUT = SPEC / "pdf-overrides-ogf.xsl"

DECLARATION = '<?xml version="1.0" encoding="UTF-8"?>\n'
FO_NAMESPACE = 'xmlns:fo="http://www.w3.org/1999/XSL/Format"'
STYLESHEET = re.compile(r"<xsl:stylesheet[^>]*>(.*)</xsl:stylesheet>", re.DOTALL)
NOTICE = """<!--
  Generated by tools/overrides.py from pdf-overrides.xsl and
  pdf-overrides-ogf-only.xsl. Do not edit it: change those and run
  `make overrides`. `make check` fails if this file is out of date.
-->
"""


def generate() -> str:
    """Return the OGF override: the shared file with the OGF templates added."""
    shared = SHARED.read_text(encoding="utf-8")
    ogf_only = OGF_ONLY.read_text(encoding="utf-8")

    body = STYLESHEET.search(ogf_only)
    if body is None:
        sys.exit(f"{OGF_ONLY.name}: no xsl:stylesheet element")
    if shared.count("</xsl:stylesheet>") != 1:
        sys.exit(f"{SHARED.name}: expected one closing xsl:stylesheet tag")

    # The OGF templates write XSL-FO directly, so the result needs its prefix.
    opening = re.search(r"<xsl:stylesheet[^>]*>", shared).group(0)
    if FO_NAMESPACE not in opening:
        widened = opening.replace(
            "<xsl:stylesheet ", f"<xsl:stylesheet {FO_NAMESPACE} ", 1
        )
        shared = shared.replace(opening, widened, 1)

    if shared.startswith(DECLARATION):
        shared = DECLARATION + NOTICE + shared[len(DECLARATION) :]
    else:
        shared = NOTICE + shared

    added = body.group(1).strip("\n")
    if not added.strip():
        return shared
    return shared.replace("</xsl:stylesheet>", f"{added}\n\n</xsl:stylesheet>")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if spec/pdf-overrides-ogf.xsl is out of date",
    )
    args = parser.parse_args(argv)

    expected = generate()
    name = OUTPUT.relative_to(SPEC.parent)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != expected:
            print(f"{name} is out of date; run `make overrides`.", file=sys.stderr)
            return 1
        print(f"{name} is up to date.")
        return 0

    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"wrote {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
